import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import test from 'node:test';
import { PrismaClient } from '@prisma/client';
import { loginAndGetCookieHeader } from './helpers/auth';
import { createTestApp } from './helpers/create-test-app';
import { usesIsolatedIntegrationDatabase } from './helpers/isolated-database';
import { canBeObjectManager } from '../src/modules/objects/utils/object-access.util';

test('creation projection and minimal personal-create-only payload preserve transaction guards', async (t) => {
  assert.equal(usesIsolatedIntegrationDatabase(), true);
  const url = new URL(process.env.DATABASE_URL!);
  assert.ok(['localhost', '127.0.0.1', '[::1]'].includes(url.hostname));
  assert.equal(url.port, '55432');
  assert.match(url.searchParams.get('schema') ?? '', /^integration_\d+_\d+$/);
  const prisma = new PrismaClient();
  const { app, baseUrl } = await createTestApp();
  t.after(async () => { try { await app.close(); } finally { await prisma.$disconnect(); } });
  const template = await prisma.user.findUniqueOrThrow({ where: { login: 'manager1' } });
  const role = await prisma.role.findUniqueOrThrow({ where: { code: 'manager' } });
  const actor = await prisma.user.create({ data: { login: `wizard-${randomUUID()}`, fullName: 'Wizard fixture', passwordHash: template.passwordHash, isActive: true, roles: { create: { roleId: role.id } } } });
  const cookie = await loginAndGetCookieHeader({ baseUrl, login: actor.login, password: 'manager123' });
  const request = (path: string, body: unknown) => fetch(`${baseUrl}/api/v1${path}`, { method: 'POST', headers: { Cookie: cookie, 'Content-Type': 'application/json' }, body: JSON.stringify(body), signal: AbortSignal.timeout(15_000) });
  const get = (path: string) => fetch(`${baseUrl}/api/v1${path}`, { headers: { Cookie: cookie }, signal: AbortSignal.timeout(15_000) });
  const references = (purpose: 'object_responsible' | 'object_manager') => get(`/users-access/users?purpose=${purpose}`);
  assert.equal((await references('object_manager')).status, 403);
  assert.equal((await references('object_responsible')).status, 403);
  const grant = await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.create', effect: 'allow', scope: 'all', selectedIds: [] } });
  let managerId = '';
  for (const purpose of ['object_responsible', 'object_manager'] as const) {
    const response = await references(purpose);
    assert.equal(response.status, 200, await response.clone().text());
    const options = await response.json() as Array<{ id: string; isActive: boolean; roleCodes: string[] }>;
    assert.ok(options.length > 0);
    assert.ok(options.every(option => option.isActive && (purpose !== 'object_manager' || canBeObjectManager(option.roleCodes))));
    assert.ok(options.every(option => Object.keys(option).every(key => ['id', 'login', 'fullName', 'isActive', 'roleCode', 'roleCodes'].includes(key))));
    if (purpose === 'object_manager') managerId = options.find(option => option.id !== actor.id)?.id ?? '';
    else assert.ok(options.some(option => option.id === actor.id));
  }
  assert.ok(managerId);
  assert.equal((await get('/users-access/admin/users')).status, 403);
  const leafDeny = await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.managers.manage', effect: 'deny', scope: 'all', selectedIds: [] } });
  assert.equal((await references('object_manager')).status, 403);
  assert.equal((await references('object_responsible')).status, 200);
  await prisma.userAccessRule.delete({ where: { id: leafDeny.id } });
  const rootDeny = await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.access', effect: 'deny', scope: 'own', selectedIds: [] } });
  assert.equal((await references('object_manager')).status, 403);
  assert.equal((await references('object_responsible')).status, 403);
  await prisma.userAccessRule.delete({ where: { id: rootDeny.id } });
  const unrelatedDeny = await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.read', effect: 'deny', scope: 'selected', selectedIds: [randomUUID()] } });
  assert.equal((await references('object_manager')).status, 200);
  assert.equal((await references('object_responsible')).status, 200);
  await prisma.userAccessRule.delete({ where: { id: unrelatedDeny.id } });
  await prisma.userAccessRule.delete({ where: { id: grant.id } });
  assert.equal((await references('object_manager')).status, 403);
  assert.equal((await references('object_responsible')).status, 403);
  await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.create', effect: 'allow', scope: 'all', selectedIds: [] } });
  const context = { status: 'active', managerUserIds: [], employeeIds: [] };
  const readCaps = async () => { const response = await request('/objects/creation-capabilities', context); assert.equal(response.status, 201, await response.clone().text()); return await response.json() as { base: boolean; rates: boolean; materials: boolean; setup: { core: boolean; budgets: boolean } }; };
  const initial = await readCaps();
  assert.equal(initial.base, true);
  assert.equal(initial.rates, false);
  assert.equal(initial.setup.core, false);
  assert.equal(initial.setup.budgets, false);
  const unknown = randomUUID();
  const unknownResponse = await request('/objects/creation-capabilities', { ...context, employeeIds: [unknown] });
  assert.equal(unknownResponse.status, 201, await unknownResponse.clone().text());
  const unknownCaps = await unknownResponse.json() as { employees: Record<string, boolean> };
  assert.deepEqual(unknownCaps.employees, { [unknown]: false });
  const minimal = { name: `minimal-${randomUUID()}`, address: 'Isolated test address', status: 'active' };
  const expectDeniedWithoutEffects = async (extra: Record<string, unknown>) => {
    const name = `team-denied-${randomUUID()}`;
    const auditBefore = await prisma.auditEvent.count({ where: { actorUserId: actor.id } });
    const objectAuditBefore = await prisma.objectAuditLog.count({ where: { actorUserId: actor.id } });
    const assignmentsBefore = await prisma.objectAssignment.count({ where: { object: { createdByUserId: actor.id } } });
    const response = await request('/objects', { ...minimal, name, ...extra });
    assert.equal(response.status, 403, await response.clone().text());
    assert.equal(await prisma.object.count({ where: { name, createdByUserId: actor.id } }), 0);
    assert.equal(await prisma.objectAssignment.count({ where: { object: { createdByUserId: actor.id } } }), assignmentsBefore);
    assert.equal(await prisma.auditEvent.count({ where: { actorUserId: actor.id } }), auditBefore);
    assert.equal(await prisma.objectAuditLog.count({ where: { actorUserId: actor.id } }), objectAuditBefore);
    assert.equal(await prisma.notification.count({ where: { type: 'object.created', body: name } }), 0);
  };
  const createRootDeny = await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.access', effect: 'deny', scope: 'own', selectedIds: [] } });
  await expectDeniedWithoutEffects({ managerUserIds: [managerId] });
  await prisma.userAccessRule.delete({ where: { id: createRootDeny.id } });
  const responsibleDeny = await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.responsibles.manage', effect: 'deny', scope: 'own', selectedIds: [] } });
  await expectDeniedWithoutEffects({ responsibleUserId: managerId });
  const defaultResponsible = await request('/objects', { ...minimal, name: `default-responsible-${randomUUID()}`, responsibleUserId: actor.id, managerUserIds: [] });
  assert.equal(defaultResponsible.status, 201, await defaultResponsible.clone().text());
  await prisma.userAccessRule.delete({ where: { id: responsibleDeny.id } });
  const managerDeny = await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.managers.manage', effect: 'deny', scope: 'own', selectedIds: [] } });
  await expectDeniedWithoutEffects({ managerUserIds: [managerId] });
  const noManagers = await request('/objects', { ...minimal, name: `no-manager-${randomUUID()}`, managerUserIds: [] });
  assert.equal(noManagers.status, 201, await noManagers.clone().text());
  await prisma.userAccessRule.delete({ where: { id: managerDeny.id } });
  const assignedDeny = await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.managers.manage', effect: 'deny', scope: 'assigned', selectedIds: [] } });
  await expectDeniedWithoutEffects({ managerUserIds: [managerId] });
  await prisma.userAccessRule.delete({ where: { id: assignedDeny.id } });
  const withTeam = await request('/objects', { ...minimal, name: `team-${randomUUID()}`, responsibleUserId: actor.id, managerUserIds: [managerId] });
  assert.equal(withTeam.status, 201, await withTeam.clone().text());
  const withOtherResponsible = await request('/objects', { ...minimal, name: `responsible-${randomUUID()}`, responsibleUserId: managerId });
  assert.equal(withOtherResponsible.status, 201, await withOtherResponsible.clone().text());
  const created = await request('/objects', minimal);
  assert.equal(created.status, 201, await created.clone().text());
  const result = await created.json() as { id: string };
  assert.equal(await prisma.object.count({ where: { id: result.id, createdByUserId: actor.id } }), 1);
  assert.equal(await prisma.objectSetup.count({ where: { objectId: result.id } }), 0);
  const deniedRate = await request('/objects', { ...minimal, name: `rate-${randomUUID()}`, dailyRate: 0 });
  assert.equal(deniedRate.status, 403);
  const deniedSetup = await request('/objects', { ...minimal, name: `setup-${randomUUID()}`, setup: {} });
  assert.equal(deniedSetup.status, 403);
  await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.rates.manage', effect: 'allow', scope: 'all', selectedIds: [] } });
  assert.equal((await readCaps()).rates, true);
  const rateGranted = await request('/objects', { ...minimal, name: `rate-allowed-${randomUUID()}`, dailyRate: 100, planning: { automaticSeasons: false } });
  assert.equal(rateGranted.status, 201, await rateGranted.clone().text());
  await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.materials.manage', effect: 'deny', scope: 'all', selectedIds: [] } });
  assert.equal((await readCaps()).materials, false);
  const deniedEmptyMaterials = await request('/objects', { ...minimal, name: `materials-denied-${randomUUID()}`, instructionSteps: [] });
  assert.equal(deniedEmptyMaterials.status, 403);
  await prisma.userAccessRule.create({ data: { userId: actor.id, actionCode: 'objects.read', effect: 'deny', scope: 'own', selectedIds: [] } });
  assert.equal((await references('object_manager')).status, 403);
  assert.equal((await references('object_responsible')).status, 403);
  assert.equal((await readCaps()).base, false);
  const denied = await request('/objects', { ...minimal, name: `denied-${randomUUID()}` });
  assert.equal(denied.status, 403);
  assert.equal(await prisma.object.count({ where: { name: { startsWith: 'denied-' }, createdByUserId: actor.id } }), 0);
});
